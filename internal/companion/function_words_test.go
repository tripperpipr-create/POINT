// Предлог — не содержание.
//
// У компаньона была своя копия разбора текста, без списка служебных слов.
// Отсюда два последствия. Ползунок строгости уточнений: правило «в сообщении
// меньше трёх значимых слов — переспроси» считало значимыми «а что по этому»,
// и при самой строгой настройке компаньон молча брался за пустую просьбу.
// И подбор отряда: совпадение по «за тем как» приносило агенту те же 12 очков,
// что совпадение по существу, и поднимало его над теми, кто подходит не хуже.
//
// Отряд собирается всегда — верхние по оценке, без порога; так же поступает и
// мастер, и здесь это не проверяется. Проверяется, что служебные слова не
// меняют порядок.
//
// Теперь правило одно на мастера и компаньона — internal/textutil.
func TestCompanionDoesNotTreatFunctionWordsAsContent(t *testing.T) {
	// Строгость 90 — человек попросил переспрашивать почти всегда.
	if !shouldAskQuestion("а что по этому", 90) {
		t.Fatal("просьба из одних служебных слов принята за содержательную")
	}
	if shouldAskQuestion("почини вебхук биллинга подписки", 90) {
		t.Fatal("содержательную задачу переспрашивать не за что")
	}

	// Второй в списке делит с задачей только служебные слова, первый — ничего.
	// По существу они равны, значит порядок обязан остаться исходным.
	agents := []domain.ProjectAgent{
		{ID: "smith", Name: "Кузнец", RoleDescription: "Собирает проект"},
		{ID: "designer", Name: "Дизайнер", RoleDescription: "Оформляет интерфейс и следит за тем, как он выглядит"},
	}
	picked := selectTeam(agents, "Почини и проверь это за тем как", 1)
	if len(picked) != 1 || picked[0] != "smith" {
		t.Fatalf("служебные слова подняли агента в отряде: %v", picked)
	}

	// Совпадение по существу порядок менять обязано.
	if picked := selectTeam(agents, "Почини интерфейс", 1); len(picked) != 1 || picked[0] != "designer" {
		t.Fatalf("настоящее совпадение перестало решать: %v", picked)
	}
}

func TestCompanionKeepsExplicitAgentName(t *testing.T) {
	tests := map[string]string{
		"Создай агента с именем QA-страж для проверки проекта":               "QA-страж",
		"Создай агента по имени «Смотритель API», который проверяет backend": "Смотритель API",
		"Create an agent named Release Guardian for deployment review":       "Release Guardian",
	}
	for request, want := range tests {
		if got := companionAgentName(request, "Шаблон"); got != want {
			t.Errorf("%q: имя %q, ожидалось %q", request, got, want)
		}
	}
	if got := companionAgentName("Создай QA агента", "Шаблон"); got != "Инженер по тестам" {
		t.Fatalf("без явного имени эвристика роли сломалась: %q", got)
	}
}
