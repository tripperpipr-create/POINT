// Единицы измерения, показанные человеку.
//
// Формат объёма был написан дважды — в hub-runtime-ui и в quest-runtime-views,
// байт в байт. Один и тот же размер контекста человек видит на двух экранах
// подряд: в инспекторе и в предпросмотре. Разойдись округление — и два числа
// об одном и том же станут спорить друг с другом.

export function formatBytes(value) {
  const bytes = Number(value || 0)
  if (bytes < 1024) return `${bytes} Б`
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(bytes < 10 * 1024 ? 1 : 0)} КиБ`
  return `${(bytes / 1024 / 1024).toFixed(1)} МиБ`
}

// Дата, показанная человеку.
//
// `new Date(x).toLocaleString('ru-RU')` звался в семи местах без защиты, и на
// неполных данных давал две беды. Пропущенная дата превращалась в «Invalid
// Date» — видно, что сломано, но непонятно что. Пустая (`null`) — в
// «01.01.1970, 07:00:00», и это хуже: правдоподобная ложь, которую человек
// принимает за настоящее время. Хаб обязан держаться на неполных данных, а
// прочерк честнее и того и другого.
export function formatDateTime(value) {
  if (value === null || value === undefined || value === '') return '—'
  const date = new Date(value)
  return Number.isNaN(date.getTime()) ? '—' : date.toLocaleString('ru-RU')
}

// Подпись кнопки, обрезанная по рунам.
//
// Имя чертежа задаёт человек, и длину ему никто не ограничивал, а подписи
// кнопок Чертога не переносятся: длинное имя выезжало за карточку и уводило
// ленту в горизонтальную прокрутку. Полное имя остаётся в подсказке.
//
// Функция жила дважды — в карточке агента и в карточке найма, — и копии уже
// разошлись пределом: 24 руны против 28. Расхождение скрытое: одно и то же
// имя на двух экранах обрезалось по-разному, и никакой текст об этом не говорил.
// Предел теперь аргумент: он виден на месте вызова, а правило одно.
export function shortLabel(name, limit) {
  const text = String(name || '')
  const runes = [...text]
  return runes.length > limit ? runes.slice(0, limit - 1).join('').trimEnd() + '\u2026' : text
}

// Список, каким бы он ни пришёл из ядра.
//
// Хаб обязан держаться на неполных данных, а `null` вместо списка — штатный ответ.
// Охранник жил четырьмя копиями в соседних карточках Мастера и двумя написаниями
// одной строки.
export function list(value) {
  return Array.isArray(value) ? value : []
}

// Русское склонение по числу — одно правило на весь вебвью.
//
// В ядре это правило уже собирали из двух копий в `internal/textutil` после того, как
// очередь решений описала набор из одного файла как «1 файлов». В вебвью копий
// снова стало две: каноническая в `view-runtime.js` и своя в карточке наряда.
//
// Затвор `ui/plural.mjs` такого не ловит: он смотрит на места вызова — на
// жёстко выбранную форму рядом с подстановкой, — а не на число определений правила.
// Вторая копия проходит его молча и разойдётся тоже молча.
export function plural(count, one, few, many) {
  const n = Math.abs(Number(count) || 0)
  const tens = n % 100
  if (tens > 10 && tens < 20) return many
  const ones = n % 10
  if (ones === 1) return one
  if (ones >= 2 && ones <= 4) return few
  return many
}

// Число и согласованная с ним форма слова вместе: разделённые, они расходятся.
export function countOf(count, one, few, many) {
  return `${Number(count) || 0} ${plural(count, one, few, many)}`
}
