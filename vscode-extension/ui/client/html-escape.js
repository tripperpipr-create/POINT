// Экранирование текста, пришедшего снаружи.
//
// Пять символов, а не три и не четыре. Копия, экранирующая меньше, не делает
// разметку безопаснее — она делает слепой проверку: смоуки карточек Мастера
// строили ожидания своим `esc` без `>` и `'` и потому подтверждали сами себя,
// а не продукт. Один закрытый дефект в этом семействе уже был —
// `REFACTOR_IDENTITY_ESCAPE_FALLBACK`, когда вместо экранирования подставилась
// функция, возвращавшая текст ядра как есть.
//
// Поэтому правило здесь одно, и его же берут смоуки: проверка не может
// экранировать слабее проверяемого, если это буквально одна функция.
const REPLACEMENTS = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;' }

export function esc(value) {
  return String(value ?? '').replace(/[&<>"']/g, character => REPLACEMENTS[character])
}
