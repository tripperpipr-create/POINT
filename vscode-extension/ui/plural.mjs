// Число из данных рядом с жёстко выбранной формой слова.
//
// «1 записей», «1 строк», «5 элемента», «1 попытки исправления» — счётчик
// подставлялся в форму, выбранную автором строки заранее. Форму обязано
// выбирать правило (countOf/plural в ui/client), потому что число приходит
// из данных и автор его не знает.
//
// Проверка текстовая и потому грубая: она смотрит на подстановку, пробел и
// русское существительное из списка. Список курируемый — это осознанный выбор:
// сплошной поиск по всем словам даёт шум, а по списку видно, что именно
// защищено. Новое считаемое слово нужно добавлять сюда руками.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const clientRoot = path.join(root, 'ui', 'client')
const sources = []
const visit = directory => {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const target = path.join(directory, entry.name)
    if (entry.isDirectory()) visit(target)
    else if (entry.isFile() && entry.name.endsWith('.js')) sources.push(target)
  }
}
visit(clientRoot)
const main = sources.sort().map(file => fs.readFileSync(file, 'utf8')).join('\n')

const NOUNS = /^(файл|файла|файлов|набор|набора|наборов|агент|агента|агентов|квест|квеста|квестов|прогон|прогона|прогонов|решение|решения|решений|запуск|запуска|запусков|ошибка|ошибки|ошибок|строка|строки|строк|символ|символа|символов|шаг|шага|шагов|правка|правки|правок|день|дня|дней|час|часа|часов|минута|минуты|минут|секунда|секунды|секунд|раз|раза|штука|штуки|штук|элемент|элемента|элементов|запись|записи|записей|контейнер|контейнера|контейнеров|образ|образа|образов|попытка|попытки|попыток|реплика|реплики|реплик|умение|умения|умений|навык|навыка|навыков|инструмент|инструмента|инструментов|шаблон|шаблона|шаблонов|правило|правила|правил|источник|источника|источников|подключение|подключения|подключений|задача|задачи|задач|проверка|проверки|проверок|ход|хода|ходов|отказ|отказа|отказов|сбой|сбоя|сбоев|узел|узла|узлов|предложение|предложения|предложений|уровень|уровня|уровней|специалист|специалиста|специалистов)$/i

// Токены исключены намеренно: это всегда крупные оценки («≈ 24 500 токенов»),
// и «0 токенов» — верная форма. Единица там практически недостижима, а пять
// мест с диапазонами («A → B токенов») пришлось бы переписывать ради случая,
// которого не бывает. Если появится счётчик токенов, способный дать 1, это
// исключение придётся снять.
const EXEMPT = /^токен(а|ов)?$/i

// Согласуется с числом не только существительное.
//
// «1 ЖДУТ РЕШЕНИЯ» в шапке Хаба проверка пропускала: сразу после подстановки
// стоит глагол, а существительное — уже за ним. Считаемое слово при этом
// глагол и есть, форму ему выбирает то же правило. Список так же курируемый,
// как и список существительных: сплошной поиск по глаголам дал бы шум.
const VERBS = /^(ждёт|ждет|ждут|осталось|остались|остался|выполняется|выполняются|запущен|запущено|запущены|найден|найдено|найдены|готов|готова|готовы)$/i

const failures = []
const lines = main.split('\n')
for (let i = 0; i < lines.length; i += 1) {
  const line = lines[i]
  if (/^\s*\/\//.test(line)) continue
  // Между числом и существительным помещается определение: «${item.shared} общ.
  // умений» проверка пропускала, потому что вплотную к подстановке стояло «общ.».
  // Разрешаем одно слово между ними — числу оно подчиняется так же.
  for (const hit of line.matchAll(/\$\{[^}]{1,80}\}\s+(?:[А-Яа-яЁё]+\.?\s+)?([А-Яа-яЁё]+)/g)) {
    const word = hit[1]
    if ((!NOUNS.test(word) && !VERBS.test(word)) || EXEMPT.test(word)) continue
    const around = line.slice(Math.max(0, hit.index - 60), hit.index + 40)
    if (/countOf\(|plural\(/.test(around)) continue
    // Виновато не обязательно то слово, что нашлось: в «${n} сбоев умений»
    // правило поймало «умений», а форму навязал автор слову «сбоев». Показываем
    // кусок целиком, иначе правку ищут не там.
    failures.push(`media/main.js:${i + 1} — «${hit[0].replace(/\s+/g, ' ')}»: форму выбирает автор строки, а не число`)
  }
}

if (failures.length) {
  console.error('СКЛОНЕНИЕ ПО ЧИСЛУ ПРОВАЛЕНО:')
  for (const line of failures) console.error('  · ' + line)
  console.error('  Используйте countOf(число, «файл», «файла», «файлов»).')
  process.exit(1)
}
console.log('склонение по числу: подстановки прикрыты правилом')
